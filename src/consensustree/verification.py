"""Explicit, opt-in execution of local Python unit tests.

WARNING: Tests execute arbitrary code in the target repository. Only use this
with repositories you trust; no sandbox is promised.
"""
from __future__ import annotations
import json
import subprocess
import sys
import time
from pathlib import Path


def run_unittest(repo: str | Path, *, consent: bool = False, timeout: int = 45) -> dict:
    if not consent:
        raise ValueError("Local tests execute repository code. Pass --unsafe-execute to consent.")
    root = Path(repo).expanduser().resolve()
    if not root.is_dir():
        raise ValueError("Test target must be a directory")
    if timeout < 1 or timeout > 180:
        raise ValueError("Timeout must be between 1 and 180 seconds")
    args = [sys.executable, "-m", "unittest", "discover", "-s", "tests", "-v"]
    started = time.monotonic()
    try:
        result = subprocess.run(args, cwd=root, stdout=subprocess.PIPE,
                                stderr=subprocess.PIPE, check=False, timeout=timeout)
        return {"verified_by": "python-unittest", "command": args, "exit_code": result.returncode,
                "passed": result.returncode == 0, "timed_out": False,
                "duration_seconds": round(time.monotonic() - started, 2),
                "output": (result.stdout + b"\n" + result.stderr)[:30000].decode("utf-8", "replace")}
    except subprocess.TimeoutExpired:
        return {"verified_by": "python-unittest", "command": args, "passed": False,
                "exit_code": None, "timed_out": True,
                "duration_seconds": round(time.monotonic() - started, 2), "output": "Test timeout"}


def write_evidence(data: dict, out: str | Path) -> None:
    target = Path(out).expanduser()
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def load_evidence(source: str | Path) -> dict:
    """Import supplied test JSON. Metadata is not authenticated."""
    path = Path(source).expanduser()
    if path.stat().st_size > 100_000:
        raise ValueError("Evidence JSON exceeds 100 KB")
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict) or payload.get("verified_by") != "python-unittest":
        raise ValueError("Expected test evidence generated by the verify command")
    if not isinstance(payload.get("passed"), bool):
        raise ValueError("Evidence missing passed boolean")
    return {k: payload.get(k) for k in ("verified_by", "passed", "exit_code", "timed_out",
                                        "duration_seconds", "output", "command")}
